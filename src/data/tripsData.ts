export const calculateMetrics = (trips: TripRecord[]) => {
  const totalViajes = trips.length;
  const viajesPropios = trips.filter(t => t.tipoTransporte === 'Propio').length;
  const viajesFleteros = trips.filter(t => t.tipoTransporte === 'Fletero').length;
  const viajesFacturados = trips.filter(t => t.estadoFacturacion === 'Facturado').length;
  const viajesPendientes = trips.filter(t => t.estadoFacturacion === 'Pendiente').length;

  const totalTnCargadas = trips.reduce((acc, t) => acc + (t.kgsCargados || 0), 0);
  const totalKmRecorridos = trips.reduce((acc, t) => acc + (t.totalKm || 0), 0);
  const facturacionNeto = trips.reduce((acc, t) => acc + (t.netoGravado || 0), 0);
  const totalIVA = trips.reduce((acc, t) => acc + (t.iva || 0), 0);
  const facturacionTotalConIVA = trips.reduce((acc, t) => acc + (t.totalFacturado || 0), 0);
  const costoFleterosTotal = trips.reduce((acc, t) => acc + (t.costoFletero || 0), 0);
  const margenBrutoTotal = trips.reduce((acc, t) => acc + (t.margenPesos || 0), 0);

  const margenBrutoPct = facturacionNeto > 0 ? margenBrutoTotal / facturacionNeto : 0;
  const tarifaPromedioPorTn = totalTnCargadas > 0 ? facturacionNeto / totalTnCargadas : 0;

  return {
    totalViajes,
    viajesPropios,
    viajesFleteros,
    viajesFacturados,
    viajesPendientes,
    totalTnCargadas,
    totalKmRecorridos,
    facturacionNeto,
    totalIVA,
    facturacionTotalConIVA,
    costoFleterosTotal,
    margenBrutoTotal,
    margenBrutoPct,
    tarifaPromedioPorTn,
  };
};
